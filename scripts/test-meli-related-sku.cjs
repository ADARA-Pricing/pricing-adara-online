const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const filename = path.resolve(__dirname, '../lib/mercadolibreRelatedSku.ts');
const loaded = new Module(filename, module);
loaded._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, filename);
const { relatedItemSkus: resolve } = loaded.exports;
const a = { id: 'MLA2042169799', seller_id: 1, item_relations: [{ id: 'MLA2042169803' }] };
const b = { id: 'MLA2042169803', seller_id: 1, sku: 'MO006', item_relations: [{ id: a.id }] };
const skus = item => item.sku ? [item.sku] : [];
const run = (first, second) => resolve(first, new Map([[first.id, first], [second.id, second]]), skus);
assert.deepEqual(run(a,b), ['MO006']);
assert.deepEqual(run({...a, sku: 'OWN'}, b), ['OWN']);
assert.deepEqual(run(a,{...b,seller_id: 2}), []);
assert.deepEqual(run(a,{...b,item_relations: []}), []);
assert.deepEqual(run({...a, variations: [{}]},b), []);
assert.deepEqual(run(a,{...b,variations: [{}]}), []);
const c = {...b, id: 'MLA3', sku: 'OTHER'};
assert.deepEqual(resolve({...a,item_relations:[...a.item_relations,{id:c.id}]}, new Map([[b.id,b],[c.id,c]]),skus), []);
console.log('OK: espejo sin SKU, SKU propio, vendedor, relación recíproca, variantes y ambigüedad.');
